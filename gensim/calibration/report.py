"""Write the v2 calibration report and the 2019-2023 step-down diagnostic to docs/.

    python -m gensim.calibration.report          # uses cached USGS / EIA data (data_cache/)
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from gensim.assets.hydro_ror import HydroParams
from gensim.calibration import hydro_calibrate as hc
from gensim.config import REPO_ROOT
from gensim.data import eia923, usgs

DOCS = REPO_ROOT / "docs"
HYPOTHESES = [  # (label, Q_max cfs, P_cap MW) from FERC EA unit data
    ("all units", None, 5.0),
    ("unit 4 out (mill units 1-3 only: 1,250 cfs, 3.05 MW)", 1250.0, 3.05),
    ("mill out (unit 4 only: 800 cfs, 2.1 MW)", 800.0, 2.1),
]


def _md(df: pd.DataFrame, floatfmt: dict | None = None) -> str:
    floatfmt = floatfmt or {}
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        cells = []
        for c, v in zip(cols, r):
            if isinstance(v, float):
                cells.append("" if np.isnan(v) else format(v, floatfmt.get(c, ",.0f")))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def build(flow: pd.DataFrame, actual: pd.DataFrame) -> dict:
    v2 = hc.run_v2(flow, actual)
    base: HydroParams = v2["params"]
    at = v2["annual"]
    ann = at[at["year"].between(2021, 2023)][["year", "actual_mwh"]].rename(columns={"actual_mwh": "actual"})
    pa, ia, ga = hc.fit_regime(flow, ann, base, "year")
    mon = actual[actual["month"].between("2021-01", "2023-12")].rename(columns={"net_generation_mwh": "actual"})
    pm, im, gm = hc.fit_regime(flow, mon, base, "month")
    hyp = []
    for label, q, cap in HYPOTHESES:
        p = HydroParams(base.head_eff_ft, q or base.q_max_cfs, base.q_minflow_cfs, 1.0, cap)
        m = hc.annual_model(flow, p).reindex([2021, 2022, 2023]).to_numpy()
        hyp.append({"hypothesis": label, "model_2021": m[0], "model_2022": m[1], "model_2023": m[2],
                    "rmse_mwh": float(np.sqrt(np.mean((m - ann["actual"].to_numpy()) ** 2)))})
    regime = HydroParams(base.head_eff_ft, pa.q_max_cfs, base.q_minflow_cfs, 1.0, pa.p_cap_mw)
    wy_reg, exc_reg = hc.water_year_scenarios(flow, regime, last=2023)
    return {"v2": v2, "regime_annual": (pa, ia, ga), "regime_monthly": (pm, im, gm),
            "hypotheses": pd.DataFrame(hyp), "regime_params": regime, "regime_exceedance": exc_reg}


def write(res: dict, docs: Path = DOCS) -> None:
    v2, m = res["v2"], res["v2"]["metrics"]
    p: HydroParams = v2["params"]
    at = v2["annual"].copy()
    table = at[at["year"].between(2001, 2024)][["year", "period", "actual_mwh", "model_mwh", "ratio_actual_to_model",
                                                "error_pct", "q_mean_cfs", "exclude_reason"]]
    table = table.rename(columns={"actual_mwh": "EIA MWh", "model_mwh": "modeled MWh (v2)", "ratio_actual_to_model": "ratio",
                                  "error_pct": "error %", "q_mean_cfs": "mean flow cfs", "exclude_reason": "flag"})
    fmt = {"ratio": ".2f", "error %": "+.1f"}

    (docs / "calibration_v2_results.md").write_text(f"""# Calibration v2 results (protocol `calibration_protocol_v2.md`)

Generated by `python -m gensim.calibration.report` from cached USGS 03164000 and EIA-923 plant 10798 data.

## Fitted parameters (availability fixed at 1.0)

| H·η (ft) | Q_max (cfs) | Q_minflow (cfs) | P_cap (MW) | at bound | annual RMSE (MWh) |
|---|---|---|---|---|---|
| {p.head_eff_ft:.2f} ({p.head_eff_ft / 39.77:.2f} × gross) | {p.q_max_cfs:,.0f} | {p.q_minflow_cfs:.0f} | {p.p_cap_mw} | {', '.join(v2['fit_info']['at_bound']) or 'none'} | {v2['fit_info']['rmse_mwh']:,.0f} |

## Acceptance

| Test | Result | Pass |
|---|---|---|
| Annual ±5%, calibrate 2003–12 | {m['calibrate']['years_within_5pct']} of {len(m['calibrate']['years_used'])} (worst {m['calibrate']['worst_abs_error_pct']:.1f}%; bias {m['calibrate']['bias_pct']:+.1f}%) | {'✅' if m['calibrate']['years_within_5pct'] == len(m['calibrate']['years_used']) else '❌'} |
| Annual ±5%, validate 2013–18 | {m['validate']['years_within_5pct']} of {len(m['validate']['years_used'])} (worst {m['validate']['worst_abs_error_pct']:.1f}%; bias {m['validate']['bias_pct']:+.1f}%) | {'✅' if m['validate']['years_within_5pct'] == len(m['validate']['years_used']) else '❌'} |
| Monthly r ≥ 0.9, metered 2017–18 | r = {m['monthly_metered']['monthly_r']:.2f} ({m['monthly_metered']['months']} months; bias {m['monthly_metered']['bias_pct']:+.1f}%) | {'✅' if m['acceptance']['monthly_r_ge_0.9_metered_2017_2018'] else '❌'} |
| 2003–16 modeled mean vs 26,150 | {m['long_run']['model_mean_mwh']:,.0f} MWh ({m['long_run']['model_vs_published_pct']:+.1f}%); EIA actual mean {m['long_run']['actual_mean_mwh']:,.0f} | {'✅' if m['acceptance']['long_run_within_5pct'] else '❌'} |

## Hydrology scenarios ("restored", v2 parameters; water years {v2['exceedance']['water_years']}, n = {v2['exceedance']['n']})

P90 **{v2['exceedance']['P90_mwh']:,.0f}** · P50 **{v2['exceedance']['P50_mwh']:,.0f}** · P10 **{v2['exceedance']['P10_mwh']:,.0f}** MWh/yr (mean {v2['exceedance']['mean_mwh']:,.0f}).

## Per-year table

{_md(table, fmt)}
""", encoding="utf-8")

    pa, ia, ga = res["regime_annual"]
    pm, im, gm = res["regime_monthly"]
    r = res["regime_params"]; e = res["regime_exceedance"]
    surf = ga.pivot(index="q_max_cfs", columns="p_cap_mw", values="rmse")
    surf = surf.loc[[400, 800, 1200, 1600, 2000], [c for c in surf.columns if c in (1.5, 2.0, 2.5, 3.0, 3.5, 5.0)]]
    surf = surf.reset_index().rename(columns=lambda c: f"P_cap {c} MW" if isinstance(c, float) else c)
    (docs / "stepdown_diagnostic.md").write_text(f"""# 2019–2023 step-down diagnostic ("as-operated" regime)

Hypothesis (Adam, 2026-11-07): unit 4 (2.1 MW Kaplan, 800 cfs) out of service.
Method: hold the v2 H·η ({p.head_eff_ft:.2f} ft) and Q_minflow ({p.q_minflow_cfs:.0f} cfs) fixed and refit Q_max
and P_cap on 2021–2023. The test as specified uses annual data (3 points); a supplementary fit on the
36 metered monthly values for 2021–2023 is shown alongside.

## Regime fit

| Data | Q_max (cfs) | P_cap (MW) | RMSE (MWh) |
|---|---|---|---|
| Annual 2021–23 (as specified) | {pa.q_max_cfs:,.0f} | {pa.p_cap_mw:.2f} | {ia['rmse']:,.0f} per year |
| Monthly metered 2021–23 (supplementary) | {pm.q_max_cfs:,.0f} | {pm.p_cap_mw:.2f} | {im['rmse']:,.0f} per month |

**The binding limit is identified; which limit binds is not.** The best fit caps output at ≈ {pa.p_cap_mw:.1f} MW.
Almost equally good: Q_max ≈ 1,200 cfs with any cap ≥ 3 MW (at the fitted head, 1,200 cfs ≈ 2.5 MW).
Both describe a plant limited to about 2.5 MW / 1,200 cfs, the mill units' rating (1,250 cfs).
Error surface (RMSE, MWh/yr):

{_md(surf, {c: ",.0f" for c in surf.columns})}

## Named hypotheses (2021–2023 annual)

{_md(res['hypotheses'], {'rmse_mwh': ',.0f'})}

**Reading:** the data favor "unit 4 out" over "mill units out" by a wide margin (RMSE ~1.2k vs
~4.7k MWh/yr). The effective limit (~2.5 MW / ~1,200 cfs) matches the mill units' hydraulic rating
(1,250 cfs). Their 3.05 MW nameplate is not reached at this head. eLibrary supports this: in July 2019
the operator filed **penstock wall repair** calculations (the concrete penstock feeds unit 4; EA §2.1.1),
followed by powerhouse intake repairs certified 2020-07 and closed 2021-05. Nothing found shows unit 4
returning to service. This is conditional on the v2 head/minimum-flow fit,
whose Q_minflow is at its bound. Treat it as supporting evidence, not confirmation. 2018 (ratio
{at.set_index('year').loc[2018, 'ratio_actual_to_model']:.2f}) may be the start of the regime, and 2019–2020 (ratios {at.set_index('year').loc[2019, 'ratio_actual_to_model']:.2f}, {at.set_index('year').loc[2020, 'ratio_actual_to_model']:.2f}) look like
deeper outages on top of it.

## "As-operated" hydrology scenarios (regime parameters on water years {e['water_years']})

P90 **{e['P90_mwh']:,.0f}** · P50 **{e['P50_mwh']:,.0f}** · P10 **{e['P10_mwh']:,.0f}** MWh/yr (mean {e['mean_mwh']:,.0f}).

## Per-year table 2001–2024 (v2 model)

{_md(table, fmt)}
""", encoding="utf-8")

    (docs / "calibration_params.json").write_text(json.dumps({
        "restored_v2": p.as_dict(), "as_operated_regime": r.as_dict(),
        "exceedance_restored": v2["exceedance"], "exceedance_as_operated": e,
    }, indent=2), encoding="utf-8")


def main():
    flow = usgs.daily_discharge("03164000")
    actual = eia923.monthly_generation(10798)
    write(build(flow, actual))
    print("wrote docs/calibration_v2_results.md, docs/stepdown_diagnostic.md, docs/calibration_params.json")


if __name__ == "__main__":
    main()
